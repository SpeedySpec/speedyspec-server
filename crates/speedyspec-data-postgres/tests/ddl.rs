//! MySQL DDL as PostgreSQL runs it: types, identity, defaults, collations, indexes, and the MySQL schema catalogue.

mod common;

use common::{WP_OPTIONS, assert_pg, wp_dialect};
use speedyspec_data::{DbError, DialectKind, Statement};
use speedyspec_data_postgres::{PgPlan, mysql_display};
use speedyspec_data_query::parse_one;

/// The emitted statements, without checking them.
fn emitted(sql: &str) -> Result<Vec<String>, DbError> {
    match wp_dialect().plan(&parse_one(sql).unwrap())? {
        PgPlan::Sql(e) => Ok(e.into_iter().map(|e| e.sql.sql).collect()),
        other => panic!("{sql}: {other:?}"),
    }
}

fn catalogue_only(statements: &[String]) -> bool {
    statements.iter().all(|s| s.contains("_speedyspec_"))
}

#[test]
fn wp_options_create() {
    let all = emitted(WP_OPTIONS).unwrap();
    let first: Vec<&str> = all.iter().take(3).map(String::as_str).collect();
    assert_eq!(
        first,
        [
            r#"CREATE TABLE "wp_options" ("option_id" BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY, "option_name" VARCHAR(191) COLLATE "speedyspec_ci" NOT NULL DEFAULT '', "option_value" TEXT COLLATE "speedyspec_ci" NOT NULL DEFAULT '', "autoload" VARCHAR(20) COLLATE "speedyspec_ci" NOT NULL DEFAULT 'yes', PRIMARY KEY ("option_id"))"#,
            r#"CREATE UNIQUE INDEX "wp_options__option_name" ON "wp_options"("option_name")"#,
            r#"CREATE INDEX "wp_options__autoload" ON "wp_options"("autoload")"#,
        ]
    );
    assert!(catalogue_only(&all[3..]), "{all:?}");
}

#[test]
fn prefix_index_name() {
    let all = emitted("CREATE TABLE wp_postmeta (meta_id bigint(20) unsigned NOT NULL auto_increment, meta_key varchar(255) default NULL, PRIMARY KEY (meta_id), KEY meta_key (meta_key(191)))").unwrap();
    assert_eq!(
        all[1],
        r#"CREATE INDEX "wp_postmeta__meta_key" ON "wp_postmeta"("meta_key")"#
    );
}

#[test]
fn type_table() {
    let all = emitted(
        "CREATE TABLE t (a tinyint(1), b int(11) unsigned, c decimal(10,2), d double, e datetime NOT NULL default '0000-00-00 00:00:00', f date, g blob, h enum('a','bb') NOT NULL default 'a', i varchar(32) COLLATE utf8mb4_bin, j timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP)",
    )
    .unwrap();
    assert!(catalogue_only(&all[1..]), "{all:?}");
    common::assert_same_pg(
        &all[0],
        r#"CREATE TABLE "t" ("a" smallint, "b" bigint, "c" numeric(10,2), "d" double precision, "e" timestamp(0) NOT NULL DEFAULT '-infinity', "f" date, "g" bytea, "h" varchar(2) COLLATE "speedyspec_ci" NOT NULL DEFAULT 'a' CHECK ("h" IN ('a', 'bb')), "i" varchar(32) COLLATE "C", "j" timestamp(0) NOT NULL DEFAULT LOCALTIMESTAMP(0))"#,
    );
}

#[test]
fn alter_forms() {
    let add =
        emitted("ALTER TABLE wp_options ADD COLUMN foo varchar(20) NOT NULL default ''").unwrap();
    assert_eq!(
        add[0],
        r#"ALTER TABLE "wp_options" ADD COLUMN "foo" VARCHAR(20) COLLATE "speedyspec_ci" NOT NULL DEFAULT ''"#
    );
    assert!(catalogue_only(&add[1..]), "{add:?}");
    let change =
        emitted("ALTER TABLE wp_posts CHANGE COLUMN post_title post_title longtext NOT NULL")
            .unwrap();
    assert_eq!(
        change[0],
        r#"ALTER TABLE "wp_posts" ALTER COLUMN "post_title" TYPE text COLLATE "speedyspec_ci", ALTER COLUMN "post_title" SET NOT NULL, ALTER COLUMN "post_title" SET DEFAULT ''"#
    );
    assert!(catalogue_only(&change[1..]), "{change:?}");
    let rename =
        emitted("ALTER TABLE wp_posts CHANGE COLUMN post_title title text NOT NULL").unwrap();
    assert_eq!(
        rename[0],
        r#"ALTER TABLE "wp_posts" RENAME COLUMN "post_title" TO "title""#
    );
    assert!(
        rename[1].starts_with(r#"ALTER TABLE "wp_posts" ALTER COLUMN "title" TYPE text"#),
        "{rename:?}"
    );
    let key = emitted("ALTER TABLE wp_postmeta ADD KEY meta_key2 (meta_key(191))").unwrap();
    assert_eq!(
        key[0],
        r#"CREATE INDEX "wp_postmeta__meta_key2" ON "wp_postmeta"("meta_key")"#
    );
    let drop = emitted("ALTER TABLE wp_postmeta DROP INDEX meta_key").unwrap();
    assert_eq!(drop[0], r#"DROP INDEX "wp_postmeta__meta_key""#);
}

#[test]
fn truncate_resets_identity() {
    assert_pg(
        &wp_dialect(),
        "TRUNCATE TABLE wp_options",
        vec![],
        &[r#"TRUNCATE TABLE "wp_options" RESTART IDENTITY"#],
    );
}

fn unsupported(sql: &str) -> String {
    match emitted(sql) {
        Err(DbError::Unsupported {
            construct,
            dialect: DialectKind::Postgres,
        }) => construct,
        other => panic!("{sql}: {other:?}"),
    }
}

#[test]
fn ddl_refusals() {
    assert_eq!(
        unsupported(
            "CREATE TABLE t (a timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP)"
        ),
        "ON UPDATE CURRENT_TIMESTAMP"
    );
    assert_eq!(
        unsupported(
            "ALTER TABLE wp_posts CHANGE COLUMN menu_order menu_order int NOT NULL auto_increment"
        ),
        "AUTO_INCREMENT added to an existing column"
    );
    // `t__<60 k>` is past PostgreSQL's 63 bytes: cut, with a hash of the whole name.
    let long = format!("CREATE TABLE t (a int, KEY {} (a))", "k".repeat(60));
    let created = emitted(&long).unwrap();
    let index = created
        .iter()
        .find(|s| s.starts_with("CREATE INDEX"))
        .unwrap_or_else(|| panic!("{created:?}"));
    let name = index.split('"').nth(1).unwrap();
    assert_eq!(name.len(), 63, "{index}");
    assert!(name.starts_with("t__kkk"), "{index}");
    let fulltext = emitted("CREATE TABLE t (a text, FULLTEXT KEY ft (a))").unwrap();
    assert!(
        !fulltext
            .iter()
            .any(|s| s.contains("t__ft") && !s.contains("_speedyspec_")),
        "{fulltext:?}"
    );
}

#[test]
fn mysql_display_matches_84() {
    assert_eq!(mysql_display("bigint(20) unsigned"), "bigint unsigned");
    assert_eq!(mysql_display("int(11)"), "int");
    assert_eq!(mysql_display("tinyint(1)"), "tinyint(1)");
    assert_eq!(mysql_display("VARCHAR(191)"), "varchar(191)");
}

