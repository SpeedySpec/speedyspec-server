<?php
// Writes src/named.rs from the pinned WordPress release's html5-named-character-references.php.
// Usage: php scripts/generate-named-references.php <wordpress-root> > src/named.rs
$wp = rtrim( $argv[1], '/' );
define( 'ABSPATH', $wp . '/' );
require "$wp/wp-includes/class-wp-token-map.php";
require "$wp/wp-includes/html-api/html5-named-character-references.php";
$all = $html5_named_character_references->to_array();
ksort( $all, SORT_STRING );
$lit = static function ( $s ) {
	$out = '';
	foreach ( str_split( $s ) as $c ) {
		$o    = ord( $c );
		$out .= ( $o >= 0x20 && $o < 0x7F && '"' !== $c && '\\' !== $c ) ? $c : sprintf( '\\x%02X', $o );
	}
	return 'b"' . $out . '"';
};
echo "//! Generated by scripts/generate-named-references.php from WordPress 7.1.5's html5-named-character-references.php.\n";
echo "//! Do not edit by hand.\n\n";
echo "/// Every HTML5 named character reference (with and without the semicolon where HTML allows both) and its UTF-8.\n";
echo "pub(crate) static NAMED: &[(&[u8], &[u8])] = &[\n";
foreach ( $all as $name => $value ) {
	echo '    (', $lit( (string) $name ), ', ', $lit( $value ), "),\n";
}
echo "];\n";
