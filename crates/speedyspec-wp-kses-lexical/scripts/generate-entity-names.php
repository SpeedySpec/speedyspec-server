<?php
// Writes src/entity_names.rs from the pinned WordPress release's kses.php globals.
// Usage: php scripts/generate-entity-names.php <wordpress-root> > src/entity_names.rs
$wp = rtrim( $argv[1], '/' );
define( 'ABSPATH', $wp . '/' );
function apply_filters( $hook, $value ) { return $value; }
function add_filter() {}
function add_action() {}
require "$wp/wp-includes/kses.php";
$emit = static function ( $const, $doc, array $names ) {
	// WordPress's own order: `wp_kses_allowed_html( 'entities' )` returns the global as it is.
	echo "/// $doc\n";
	echo "pub(crate) static $const: &[&[u8]] = &[\n";
	foreach ( $names as $name ) {
		echo "    b\"$name\",\n";
	}
	echo "];\n";
};
echo "//! Generated by scripts/generate-entity-names.php from WordPress 7.1.5's kses.php. Do not edit by hand.\n\n";
$emit( 'HTML_ENTITY_NAMES', '`$allowedentitynames`.', $allowedentitynames );
echo "\n";
$emit( 'XML_ENTITY_NAMES', '`$allowedxmlentitynames`.', $allowedxmlentitynames );
