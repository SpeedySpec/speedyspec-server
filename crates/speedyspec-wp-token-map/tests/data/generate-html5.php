<?php
/**
 * Writes src/html5_table.rs: WordPress's HTML5 named character reference table (the state
 * html5-named-character-references.php builds with WP_Token_Map::from_precomputed_table()) as Rust statics.
 *
 * Usage: .php-build/buildroot/bin/php generate-html5.php <wordpress-root>
 */

[$_, $root] = $argv + [null, null];
$root = rtrim($root, '/') . '/';
function __($t) { return $t; }
function _doing_it_wrong() {}
require $root . 'wp-includes/version.php';
require $root . 'wp-includes/class-wp-token-map.php';
require $root . 'wp-includes/html-api/html5-named-character-references.php';

$map = $html5_named_character_references;
$state = array();
foreach (array('key_length', 'groups', 'large_words', 'small_words', 'small_mappings') as $p) {
    $prop = new ReflectionProperty($map, $p);
    $state[$p] = $prop->getValue($map);
}

/** A Rust byte string literal. */
function speedyspec_bytes(string $s): string {
    $out = 'b"';
    for ($i = 0; $i < strlen($s); $i++) {
        $c = ord($s[$i]);
        if (34 === $c || 92 === $c) {
            $out .= '\\' . $s[$i];
        } elseif ($c >= 32 && $c < 127) {
            $out .= $s[$i];
        } else {
            $out .= sprintf('\\x%02x', $c);
        }
    }
    return $out . '"';
}

$rs = "//! WordPress {$wp_version}'s HTML5 named character reference table, the state `html5-named-character-references.php`\n";
$rs .= "//! builds with `WP_Token_Map::from_precomputed_table()`. Generated by `tests/data/generate-html5.php`; do not edit.\n\n";
$rs .= "pub(crate) const KEY_LENGTH: usize = {$state['key_length']};\n\n";
$rs .= 'pub(crate) const GROUPS: &[u8] = ' . speedyspec_bytes($state['groups']) . ";\n\n";
$rs .= "pub(crate) const LARGE_WORDS: &[&[u8]] = &[\n";
foreach ($state['large_words'] as $w) {
    $rs .= '    ' . speedyspec_bytes($w) . ",\n";
}
$rs .= "];\n\n";
$rs .= 'pub(crate) const SMALL_WORDS: &[u8] = ' . speedyspec_bytes($state['small_words']) . ";\n\n";
$rs .= "pub(crate) const SMALL_MAPPINGS: &[&[u8]] = &[\n";
foreach ($state['small_mappings'] as $m) {
    $rs .= '    ' . speedyspec_bytes($m) . ",\n";
}
$rs .= "];\n";
file_put_contents(dirname(__DIR__, 2) . '/src/html5_table.rs', $rs);
echo count($state['large_words']), " groups, ", count($state['small_mappings']), " small words\n";
