//! `php-tables`: prints a generated table, so the port uses exactly PHP's or WordPress's data.
//!
//! - `php-tables` (or `php-tables html401`): `speedyspec-wp-text-escape/src/html401.rs`, the HTML 4.01 entity table,
//!   from the embedded PHP's own `get_html_translation_table()`.
//! - `php-tables ent2ncr <wp-includes/formatting.php>`: `speedyspec-wp-text/src/ent2ncr_table.rs`, the `$to_ncr`
//!   array of that release's `ent2ncr()`, in its order.
//! - `php-tables mb-lower`: `speedyspec-wp-text/src/mb_lower_table.rs`, the code points where the embedded PHP's
//!   `mb_strtolower()` and Rust's `char::to_lowercase()` disagree.
//! - `php-tables remove-accents <wp-includes/formatting.php>`: `speedyspec-wp-text/src/accents_table.rs`, the
//!   `$chars` array of that release's `remove_accents()`, in its order.
//! - `php-tables mime-types <wp-includes/functions.php>`: `speedyspec-wp-text/src/adapters/mime_table.rs`, the
//!   default array of that release's `wp_get_mime_types()`, in its order.

use std::rc::Rc;

use speedyspec_hooks::Value;
use speedyspec_hooks_memory::MemoryHooks;
use speedyspec_php::{BootOptions, Php};

const DUMP: &str = r#"
function speedyspec_formatting_html401(): string
{
    $table = get_html_translation_table(HTML_ENTITIES, ENT_QUOTES | ENT_HTML401, 'UTF-8');
    $out = [];
    foreach ($table as $char => $entity) {
        $out[] = [bin2hex((string) $char), $entity];
    }
    return json_encode($out, JSON_THROW_ON_ERROR);
}

function speedyspec_formatting_ent2ncr(string $file): string
{
    $source = (string) file_get_contents($file);
    if (!preg_match('/function ent2ncr\(.*?\$to_ncr\s*=\s*(array\(.*?\));/s', $source, $m)) {
        throw new RuntimeException("no \$to_ncr in $file");
    }
    $to_ncr = eval('return ' . $m[1] . ';');
    $out = [];
    foreach ($to_ncr as $entity => $ncr) {
        $out[] = [$entity, $ncr];
    }
    return json_encode($out, JSON_THROW_ON_ERROR);
}

function speedyspec_formatting_mb_lower(): string
{
    $out = [];
    for ($cp = 0; $cp <= 0x10FFFF; $cp++) {
        if ($cp >= 0xD800 && $cp <= 0xDFFF) {
            continue;
        }
        $char = mb_chr($cp, 'UTF-8');
        $lower = mb_strtolower($char, 'UTF-8');
        if ($lower !== $char) {
            $out[] = [$cp, $lower];
        }
    }
    return json_encode($out, JSON_THROW_ON_ERROR);
}

function speedyspec_formatting_array_in(string $file, string $pattern): string
{
    $source = (string) file_get_contents($file);
    if (!preg_match($pattern, $source, $m)) {
        throw new RuntimeException("$pattern: not found in $file");
    }
    $array = eval('return ' . $m[1] . ';');
    $out = [];
    foreach ($array as $key => $value) {
        $out[] = [(string) $key, $value];
    }
    return json_encode($out, JSON_THROW_ON_ERROR);
}
"#;

/// Calls one of `DUMP`'s functions and decodes its JSON.
fn dump<T: serde::de::DeserializeOwned>(php: &Php, function: &str, args: &[Value]) -> T {
    let Value::Str(json) = php.call(&Value::Str(function.into()), args).expect("runs") else {
        panic!("not a string");
    };
    serde_json::from_str(&json).expect("json")
}

/// Prints a `&[(&str, &str)]` table.
fn print_pairs(name: &str, doc: &str, pairs: &[(String, String)]) {
    println!("/// {doc}");
    println!("pub(crate) static {name}: &[(&str, &str)] = &[");
    for (a, b) in pairs {
        println!("    ({a:?}, {b:?}),");
    }
    println!("];");
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let php = Php::boot(BootOptions {
        hooks: Rc::new(MemoryHooks::new()),
        preload: &[],
        areas: Vec::new(),
    })
    .expect("PHP starts");
    php.eval("speedyspec://formatting/tables", DUMP).expect("loads");
    match args.first().map(String::as_str) {
        Some("mb-lower") => {
            let php_lower: Vec<(u32, String)> = dump(&php, "speedyspec_formatting_mb_lower", &[]);
            let php_map: std::collections::HashMap<u32, String> = php_lower.into_iter().collect();
            let mut differ: Vec<(char, String)> = Vec::new();
            for cp in 0..=0x10FFFFu32 {
                let Some(c) = char::from_u32(cp) else { continue };
                let rust: String = c.to_lowercase().collect();
                let php = php_map.get(&cp).cloned().unwrap_or_else(|| c.to_string());
                if rust != php {
                    differ.push((c, php));
                }
            }
            println!("//! Where PHP's `mb_strtolower()` and Rust's `char::to_lowercase()` disagree, generated by");
            println!("//! `cargo run -p speedyspec-wp-text-corpus --features php --bin php-tables -- mb-lower` from the");
            println!("//! embedded PHP's mbstring. Do not edit by hand.");
            println!();
            println!("/// Each code point whose PHP lowercase differs from Rust's, and PHP's lowercase, sorted.");
            println!("pub(crate) static MB_LOWER_EXCEPTIONS: &[(char, &str)] = &[");
            for (c, lower) in &differ {
                println!("    ({c:?}, {lower:?}),");
            }
            println!("];");
            return;
        }
        Some("remove-accents") => {
            let file = args.get(1).expect("php-tables remove-accents <wp-includes/formatting.php>");
            let pattern = r"/function remove_accents\(.*?\$chars\s*=\s*(array\(.*?\n\t\t\));/s";
            let pairs: Vec<(String, String)> = dump(
                &php,
                "speedyspec_formatting_array_in",
                &[Value::Str(file.clone()), Value::Str(pattern.into())],
            );
            println!("//! `remove_accents()`'s table, generated by");
            println!("//! `cargo run -p speedyspec-wp-text-corpus --features php --bin php-tables -- remove-accents <formatting.php>`");
            println!("//! from WordPress 7.1.5's `$chars`. Do not edit by hand.");
            println!();
            print_pairs("ACCENTS", "Each character `remove_accents()` replaces in UTF-8 text and its replacement, in WordPress's order.", &pairs);
            return;
        }
        Some("mime-types") => {
            let file = args.get(1).expect("php-tables mime-types <wp-includes/functions.php>");
            let pattern = r"/function wp_get_mime_types\(.*?'mime_types',\s*(array\(.*?\n\t\t\))/s";
            let pairs: Vec<(String, String)> = dump(
                &php,
                "speedyspec_formatting_array_in",
                &[Value::Str(file.clone()), Value::Str(pattern.into())],
            );
            println!("//! `wp_get_mime_types()`'s default table, generated by");
            println!("//! `cargo run -p speedyspec-wp-text-corpus --features php --bin php-tables -- mime-types <functions.php>`");
            println!("//! from WordPress 7.1.5. Do not edit by hand.");
            println!();
            print_pairs("MIME_TYPES", "Each extension pattern and its MIME type, in WordPress's order, before the `mime_types` filter.", &pairs);
            return;
        }
        _ => {}
    }
    if args.first().map(String::as_str) == Some("ent2ncr") {
        let file = args.get(1).expect("php-tables ent2ncr <wp-includes/formatting.php>");
        let Value::Str(json) = php
            .call(&Value::Str("speedyspec_formatting_ent2ncr".into()), &[Value::Str(file.clone())])
            .expect("runs")
        else {
            panic!("not a string");
        };
        let pairs: Vec<(String, String)> = serde_json::from_str(&json).expect("json");
        println!("//! `ent2ncr()`'s table, generated by");
        println!("//! `cargo run -p speedyspec-wp-text-corpus --features php --bin php-tables -- ent2ncr <formatting.php>`");
        println!("//! from WordPress 7.1.5's `$to_ncr`. Do not edit by hand.");
        println!();
        println!("/// Each named entity `ent2ncr()` converts and its numeric reference, in WordPress's order.");
        println!("pub(crate) static ENT2NCR: &[(&str, &str)] = &[");
        for (entity, ncr) in &pairs {
            println!("    ({entity:?}, {ncr:?}),");
        }
        println!("];");
        return;
    }
    let Value::Str(json) = php
        .call(&Value::Str("speedyspec_formatting_html401".into()), &[])
        .expect("runs")
    else {
        panic!("not a string");
    };
    let pairs: Vec<(String, String)> = serde_json::from_str(&json).expect("json");
    let mut names: Vec<&str> = pairs
        .iter()
        .filter_map(|(_, entity)| entity.strip_prefix('&')?.strip_suffix(';'))
        .filter(|name| !name.starts_with('#'))
        .collect();
    names.sort_unstable();
    println!("//! The HTML 4.01 entity table, generated by");
    println!("//! `cargo run -p speedyspec-wp-text-corpus --features php --bin php-tables` from the embedded PHP's");
    println!("//! `get_html_translation_table(HTML_ENTITIES, ENT_QUOTES | ENT_HTML401, 'UTF-8')`. Do not edit by hand.");
    println!();
    println!("/// The entity names PHP recognizes in HTML 4.01, sorted for binary search.");
    println!("pub(crate) static HTML401_NAMES: &[&str] = &[");
    for name in &names {
        println!("    {name:?},");
    }
    println!("];");
    println!();
    println!("/// Each character PHP's `HTML_ENTITIES` table translates, and its entity, in PHP's order.");
    println!("pub(crate) static HTML401_TABLE: &[(&[u8], &str)] = &[");
    for (hex, entity) in &pairs {
        let bytes: Vec<String> = (0..hex.len())
            .step_by(2)
            .map(|i| format!("0x{}", &hex[i..i + 2]))
            .collect();
        println!("    (&[{}], {entity:?}),", bytes.join(", "));
    }
    println!("];");
}
