//! `php-tables`: prints a generated table, so the port uses exactly PHP's or WordPress's data.
//!
//! - `php-tables` (or `php-tables html401`): `speedyspec-wp-text-escape/src/html401.rs`, the HTML 4.01 entity table,
//!   from the embedded PHP's own `get_html_translation_table()`.
//! - `php-tables ent2ncr <wp-includes/formatting.php>`: `speedyspec-wp-text/src/ent2ncr_table.rs`, the `$to_ncr`
//!   array of that release's `ent2ncr()`, in its order.

use std::rc::Rc;

use speedyspec_hooks::Value;
use speedyspec_hooks_memory::MemoryHooks;
use speedyspec_php::{BootOptions, Php};

const DUMP: &str = r#"
function speedyspec_formatting_html401(): string
{
    $table = get_html_translation_table(HTML_ENTITIES, ENT_QUOTES | ENT_HTML401, 'UTF-8');
    $out = [];
    foreach ($table as $char => $entity) {
        $out[] = [bin2hex((string) $char), $entity];
    }
    return json_encode($out, JSON_THROW_ON_ERROR);
}

function speedyspec_formatting_ent2ncr(string $file): string
{
    $source = (string) file_get_contents($file);
    if (!preg_match('/function ent2ncr\(.*?\$to_ncr\s*=\s*(array\(.*?\));/s', $source, $m)) {
        throw new RuntimeException("no \$to_ncr in $file");
    }
    $to_ncr = eval('return ' . $m[1] . ';');
    $out = [];
    foreach ($to_ncr as $entity => $ncr) {
        $out[] = [$entity, $ncr];
    }
    return json_encode($out, JSON_THROW_ON_ERROR);
}
"#;

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let php = Php::boot(BootOptions {
        hooks: Rc::new(MemoryHooks::new()),
        preload: &[],
        areas: Vec::new(),
    })
    .expect("PHP starts");
    php.eval("speedyspec://formatting/tables", DUMP).expect("loads");
    if args.first().map(String::as_str) == Some("ent2ncr") {
        let file = args.get(1).expect("php-tables ent2ncr <wp-includes/formatting.php>");
        let Value::Str(json) = php
            .call(&Value::Str("speedyspec_formatting_ent2ncr".into()), &[Value::Str(file.clone())])
            .expect("runs")
        else {
            panic!("not a string");
        };
        let pairs: Vec<(String, String)> = serde_json::from_str(&json).expect("json");
        println!("//! `ent2ncr()`'s table, generated by");
        println!("//! `cargo run -p speedyspec-wp-text-corpus --features php --bin php-tables -- ent2ncr <formatting.php>`");
        println!("//! from WordPress 7.1.5's `$to_ncr`. Do not edit by hand.");
        println!();
        println!("/// Each named entity `ent2ncr()` converts and its numeric reference, in WordPress's order.");
        println!("pub(crate) static ENT2NCR: &[(&str, &str)] = &[");
        for (entity, ncr) in &pairs {
            println!("    ({entity:?}, {ncr:?}),");
        }
        println!("];");
        return;
    }
    let Value::Str(json) = php
        .call(&Value::Str("speedyspec_formatting_html401".into()), &[])
        .expect("runs")
    else {
        panic!("not a string");
    };
    let pairs: Vec<(String, String)> = serde_json::from_str(&json).expect("json");
    let mut names: Vec<&str> = pairs
        .iter()
        .filter_map(|(_, entity)| entity.strip_prefix('&')?.strip_suffix(';'))
        .filter(|name| !name.starts_with('#'))
        .collect();
    names.sort_unstable();
    println!("//! The HTML 4.01 entity table, generated by");
    println!("//! `cargo run -p speedyspec-wp-text-corpus --features php --bin php-tables` from the embedded PHP's");
    println!("//! `get_html_translation_table(HTML_ENTITIES, ENT_QUOTES | ENT_HTML401, 'UTF-8')`. Do not edit by hand.");
    println!();
    println!("/// The entity names PHP recognizes in HTML 4.01, sorted for binary search.");
    println!("pub(crate) static HTML401_NAMES: &[&str] = &[");
    for name in &names {
        println!("    {name:?},");
    }
    println!("];");
    println!();
    println!("/// Each character PHP's `HTML_ENTITIES` table translates, and its entity, in PHP's order.");
    println!("pub(crate) static HTML401_TABLE: &[(&[u8], &str)] = &[");
    for (hex, entity) in &pairs {
        let bytes: Vec<String> = (0..hex.len())
            .step_by(2)
            .map(|i| format!("0x{}", &hex[i..i + 2]))
            .collect();
        println!("    (&[{}], {entity:?}),", bytes.join(", "));
    }
    println!("];");
}
