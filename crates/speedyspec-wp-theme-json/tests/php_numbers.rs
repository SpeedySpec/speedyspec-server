#[test]
fn round_matches_php() {
    for (value, _, two, zero) in ROWS {
        assert_eq!(
            float_to_string(round(*value, 2)),
            *two,
            "round({value:?}, 2)"
        );
        assert_eq!(
            float_to_string(round(*value, 0)),
            *zero,
            "round({value:?}, 0)"
        );
    }
}
