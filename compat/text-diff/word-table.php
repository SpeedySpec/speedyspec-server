<?php
/**
 * Prints the Rust table of non-ASCII code points that `\w` matches under `/u`, from this PHP's own PCRE.
 *
 * Usage: php word-table.php > crates/speedyspec-wp-text-diff/src/words/table.rs
 *
 * Run it with the static PHP the port embeds, so the table is that PCRE's (PCRE2 10.44, Unicode 15.0.0).
 */

declare(strict_types=1);

$ranges = array();
$start = null;
for ($cp = 0x80; $cp <= 0x110000; $cp++) {
    $is = $cp < 0x110000 && ($cp < 0xD800 || $cp > 0xDFFF) && preg_match('/^\w$/u', mb_chr($cp, 'UTF-8')) === 1;
    if ($is && $start === null) {
        $start = $cp;
    } elseif (!$is && $start !== null) {
        $ranges[] = array($start, $cp - 1);
        $start = null;
    }
}
echo "//! Non-ASCII code points that PCRE's `\\w` matches under `/u`, as inclusive ranges, sorted.\n";
echo "//!\n";
echo "//! Generated by `compat/text-diff/word-table.php` from PCRE " . PCRE_VERSION . " (PHP " . PHP_VERSION . "). Do not edit.\n\n";
echo "pub(super) const WORD_RANGES: &[(u32, u32)] = &[\n";
foreach ($ranges as $r) {
    printf("    (0x%X, 0x%X),\n", $r[0], $r[1]);
}
echo "];\n";
