#!/usr/bin/env bash
# Tests scripts/platform-local.sh against a throwaway platform checkout.
set -euo pipefail

script="$(cd "$(dirname "$0")/.." && pwd)/platform-local.sh"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
work="$(cd "$work" && pwd -P)"

failures=0
fail() {
    echo "FAIL: $*" >&2
    failures=$((failures + 1))
}

platform="$work/platform"
mkdir -p "$platform/scripts" "$platform/crates/speedyspec-hooks" "$platform/crates/speedyspec-php"
touch "$platform/crates/speedyspec-hooks/Cargo.toml" "$platform/crates/speedyspec-php/Cargo.toml"
printf '%s\n' '# publishing order' '' 'speedyspec-hooks' '  # indented comment' 'speedyspec-php' \
    >"$platform/scripts/publish-crates.txt"

# A relative checkout, the default output: absolute paths, one per listed crate, comments and blanks skipped.
mkdir -p "$work/server"
(cd "$work/server" && "$script" ../platform)
want="# Generated by scripts/platform-local.sh from $platform. Do not commit.
[patch.crates-io]
speedyspec-hooks = { path = \"$platform/crates/speedyspec-hooks\" }
speedyspec-php = { path = \"$platform/crates/speedyspec-php\" }"
if [ "$(cat "$work/server/platform.local.toml")" = "$want" ]; then
    echo "ok: default output"
else
    fail "default output: $(cat "$work/server/platform.local.toml")"
fi

# An explicit output path.
"$script" "$platform" "$work/out.toml"
if [ "$(cat "$work/out.toml")" = "$want" ]; then echo "ok: explicit output"; else fail "explicit output"; fi

# A listed crate missing from crates/: fails and writes nothing.
echo 'speedyspec-gone' >>"$platform/scripts/publish-crates.txt"
status=0
"$script" "$platform" "$work/missing.toml" 2>/dev/null || status=$?
if [ "$status" = 1 ] && [ ! -e "$work/missing.toml" ] && [ ! -e "$work/missing.toml.tmp" ]; then echo "ok: missing crate"; else fail "missing crate: exit $status"; fi

# Not a platform checkout, and no arguments.
status=0
"$script" "$work/server" "$work/x.toml" 2>/dev/null || status=$?
if [ "$status" = 2 ]; then echo "ok: not a checkout"; else fail "not a checkout: exit $status"; fi
status=0
"$script" 2>/dev/null || status=$?
if [ "$status" = 2 ]; then echo "ok: usage"; else fail "usage: exit $status"; fi

if [ "$failures" -ne 0 ]; then
    echo "$failures failed" >&2
    exit 1
fi
echo "all passed"
