#!/usr/bin/env bash
# Points this workspace's platform crates at a local speedyspec-platform checkout, for work that spans both
# repositories (a contracts change and its server implementation, or a CI proof against an unreleased platform).
#
#   scripts/platform-local.sh <platform-checkout> [output]
#
# Writes <output> (default: platform.local.toml in the current directory, which .gitignore ignores) with a
# `[patch.crates-io]` line for each crate in the checkout's scripts/publish-crates.txt:
#
#   speedyspec-hooks = { path = "/abs/platform/crates/speedyspec-hooks" }
#
# The paths are absolute, so the file works with `cargo --config platform.local.toml ...` and appended to
# .cargo/config.toml. Never commit the patch: scripts/check-no-platform-patch.sh fails a committed one.
set -euo pipefail

if [ "$#" -lt 1 ] || [ "$#" -gt 2 ]; then
    echo "usage: scripts/platform-local.sh <platform-checkout> [output]" >&2
    exit 2
fi
if ! checkout="$(cd "$1" 2>/dev/null && pwd)"; then
    echo "platform-local.sh: $1 is not a directory" >&2
    exit 2
fi
output="${2:-platform.local.toml}"
list="$checkout/scripts/publish-crates.txt"
if [ ! -f "$list" ]; then
    echo "platform-local.sh: $checkout has no scripts/publish-crates.txt (is it a speedyspec-platform checkout?)" >&2
    exit 2
fi

trap 'rm -f "$output.tmp"' EXIT
{
    echo "# Generated by scripts/platform-local.sh from $checkout. Do not commit."
    echo "[patch.crates-io]"
    grep -v -e '^[[:space:]]*$' -e '^[[:space:]]*#' "$list" | while read -r crate; do
        if [ ! -f "$checkout/crates/$crate/Cargo.toml" ]; then
            echo "platform-local.sh: $list names $crate, which $checkout/crates/ does not hold" >&2
            exit 1
        fi
        echo "$crate = { path = \"$checkout/crates/$crate\" }"
    done
} >"$output.tmp"
mv "$output.tmp" "$output"
