#!/usr/bin/env bash
# Builds the static PHP that speedyspec-server embeds (copied from packages/speedyspec-cli and extended).
#
# Downloads a pinned static-php-cli (`spc`) binary for the host, writes
# craft.yml from the version in ./php-version, and runs `spc craft`. The result
# is .php-build/buildroot with lib/libphp.a (embed SAPI) and bin/php-config.
# See docs/php-embed.md for why each setting is what it is.
#
# By default nothing outside the repository is installed or changed: missing
# build tools are reported with an install hint and the script fails. Set
# SPEEDYSPEC_ALLOW_HOST_INSTALL=1 to let `spc doctor --auto-fix` install them
# (Homebrew on macOS, the distro package manager on Linux); scripts/linux.sh
# and CI do, since they run in throwaway environments.
set -euo pipefail

repo="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
build_dir="$repo/.php-build"

# static-php-cli 2.8.6, nightly channel on dl.static-php.dev (published
# 2026-08-22). The nightly URL is mutable; the checksum is what pins the
# version. A mismatch means upstream moved: re-pin deliberately.
spc_base_url="https://dl.static-php.dev/static-php-cli/spc-bin/nightly"

case "$(uname -s)-$(uname -m)" in
    Darwin-arm64)   spc_name="spc-macos-aarch64";  spc_sha256="9eba2e6e0d1aebabd6ff8efc6711dd0bad335ba41e29ce36e06ea5a6c5d57731" ;;
    Darwin-x86_64)  spc_name="spc-macos-x86_64";   spc_sha256="07ff81f18cbb34f24ca2ba95f5c0554d407b9fd782dd9081b25b1250160ab0f5" ;;
    Linux-x86_64)   spc_name="spc-linux-x86_64";   spc_sha256="c138f3e4a68479597e11ca14d5209346c54758ccd09005e7a6a6f1e63b7f9f71" ;;
    Linux-aarch64)  spc_name="spc-linux-aarch64";  spc_sha256="26f483093b97da2925e4e993036c59509eab28656346b505d2d0a11271faae99" ;;
    *) echo "build-php.sh: unsupported host $(uname -s)-$(uname -m)" >&2; exit 1 ;;
esac

# libsodium 1.0.22, which ext-sodium links and the Rust crypto port calls (one copy for both). spc would otherwise
# fetch whatever libsodium its source list resolves to at download time, so the build fetches this exact tarball
# itself, checks it, and hands it to spc. The checksum was checked against the release's minisign signature
# (libsodium's key RWQf6LRCGA9i53mlYecO4IzT51TGPpvWucNSCh1CBM0QTaLn73Y7GFO3). WordPress needs ext-sodium and the
# runtime refuses to start without it, so a build without this exact libsodium fails.
libsodium_version="1.0.22"
libsodium_url="https://download.libsodium.org/libsodium/releases/libsodium-$libsodium_version.tar.gz"
libsodium_sha256="adbdd8f16149e81ac6078a03aca6fc03b592b89ef7b5ed83841c086191be3349"

sha256_of() {
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$1" | cut -d' ' -f1
    else
        shasum -a 256 "$1" | cut -d' ' -f1
    fi
}

php_version="$(tr -d '[:space:]' < "$repo/php-version")"

# The oldest macOS the binary runs on. Must match .cargo/config.toml, which sets
# it for the Rust side; it is part of the stamp so a change rebuilds PHP.
deployment_target=""
if [ "$(uname -s)" = "Darwin" ]; then
    export MACOSX_DEPLOYMENT_TARGET="${MACOSX_DEPLOYMENT_TARGET:-12.0}"
    deployment_target="$MACOSX_DEPLOYMENT_TARGET"
fi
# Every extension WordPress's Site Health checks for, plus what WordPress otherwise relies on
# (docs/superpowers/specs/2026-11-18-speedyspec-php-foundation-design.md, "The PHP build"). A hard requirement:
# if one will not build, stop; never drop it quietly.
extensions="bcmath,ctype,curl,dom,exif,fileinfo,filter,gd,iconv,imagick,intl,mbstring,mysqli,mysqlnd,opcache,openssl,pdo,pdo_mysql,pdo_sqlite,phar,session,simplexml,sodium,sqlite3,tokenizer,xml,xmlreader,xmlwriter,zip,zlib"
# gd's optional formats WordPress uses: JPEG, PNG, WebP, AVIF and FreeType fonts.
libs="libjpeg,libpng,libwebp,libavif,freetype"

# `cli` is built only because ext-php-rs's build script runs `php -i` to read
# the API version and thread safety. The CLI binary is never shipped.
#
# On Linux the CLI links static-pie with --export-dynamic. Exporting libstdc++'s
# thread-local std::__once_call leaves R_X86_64_TPOFF64 relocations that musl's
# static-pie startup never applies, so ICU's first std::call_once jumps to garbage
# and every intl call that loads ICU data crashes (x86_64 only; aarch64's linker
# resolves them). --exclude-libs,ALL keeps static archives' symbols out of the
# export list. spc puts EXTRA_CFLAGS on the CLI's link line, so the flag rides
# there; the rest is spc's Linux default.
extra_env=""
if [ "$(uname -s)" = "Linux" ]; then
    extra_env='extra-env:
  SPC_CMD_VAR_PHP_MAKE_EXTRA_CFLAGS: "-g -fstack-protector-strong -fno-ident -fPIE -fPIC -Os -Wl,--exclude-libs,ALL"'
fi
mkdir -p "$build_dir"
libsodium_tarball="$build_dir/pinned/libsodium-$libsodium_version.tar.gz"
cat > "$repo/craft.yml" <<EOF
# Generated by scripts/build-php.sh from ./php-version. Do not edit by hand.
php-version: "$php_version"
extensions: "$extensions"
libs: "$libs"
sapi:
  - embed
  - cli
# craft must not run spc doctor --auto-fix, which installs host packages;
# build-php.sh checks the tools itself (see SPEEDYSPEC_ALLOW_HOST_INSTALL).
craft-options:
  doctor: false
# The pinned libsodium, fetched and checked by build-php.sh (see libsodium_sha256).
download-options:
  custom-url:
    - "libsodium:file://$libsodium_tarball"
EOF
if [ -n "$extra_env" ]; then
    printf '%s\n' "$extra_env" >> "$repo/craft.yml"
fi

# A buildroot made from this exact craft.yml by this exact spc is reused (CI
# restores it from cache); anything else, a re-pinned spc included, is rebuilt.
stamp="$build_dir/buildroot/.craft.yml"
stamp_content="$(cat "$repo/craft.yml")
# spc: $spc_name sha256=$spc_sha256
# macOS deployment target: ${deployment_target:-none}
# libsodium: $libsodium_version sha256=$libsodium_sha256"

# Fails unless the buildroot has ext-sodium on the pinned libsodium: the archive, its link flag, and the version
# PHP reports.
check_sodium() {
    local lib="$build_dir/buildroot/lib/libsodium.a" got
    if [ ! -f "$lib" ]; then
        echo "build-php.sh: sodium: $lib was not produced; ext-sodium is required" >&2
        exit 1
    fi
    if ! grep -Eq '(^|[[:space:]])-lsodium([[:space:]]|$)' "$build_dir/buildroot/link-flags.txt"; then
        echo "build-php.sh: sodium: link-flags.txt has no -lsodium; ext-sodium is required" >&2
        exit 1
    fi
    got="$("$build_dir/buildroot/bin/php" -n -r 'echo extension_loaded("sodium") ? SODIUM_LIBRARY_VERSION : "none";')"
    if [ "$got" != "$libsodium_version" ]; then
        echo "build-php.sh: sodium: expected libsodium $libsodium_version, PHP reports $got" >&2
        exit 1
    fi
}
if [ -f "$build_dir/buildroot/lib/libphp.a" ] && [ -f "$stamp" ] \
    && [ "$(cat "$stamp")" = "$stamp_content" ]; then
    check_sodium
    echo "build-php.sh: $build_dir/buildroot is up to date"
    exit 0
fi

# Read-only check for the host tools static-php-cli needs (the commands its
# `spc doctor` checks for). Fails with an install hint instead of installing.
preflight() {
    local missing=() tools cmd bison_ok=""
    case "$(uname -s)" in
        Darwin) tools="curl make re2c flex git autoconf automake tar libtool unzip xz gzip bzip2 cmake glibtoolize" ;;
        *)      tools="curl make re2c flex git autoconf automake tar unzip xz gzip bzip2 cmake gcc g++ patch libtoolize perl which" ;;
    esac
    for cmd in $tools; do
        command -v "$cmd" >/dev/null 2>&1 || missing+=("$cmd")
    done
    # PHP needs bison 3+. macOS ships 2.3; Homebrew's bison is keg-only, and
    # spc looks in its keg directory too.
    for cmd in "$(command -v bison || true)" /opt/homebrew/opt/bison/bin/bison /usr/local/opt/bison/bin/bison; do
        if [ -n "$cmd" ] && [ -x "$cmd" ] && "$cmd" --version 2>/dev/null | head -1 | grep -Eq ' [3-9]\.'; then
            bison_ok=1
            break
        fi
    done
    [ -n "$bison_ok" ] || missing+=("bison>=3")

    if [ "${#missing[@]}" -gt 0 ]; then
        echo "build-php.sh: missing build tools: ${missing[*]}" >&2
        case "$(uname -s)" in
            Darwin) echo "  install with: brew install autoconf automake bison bzip2 cmake flex git libtool make re2c xz" >&2 ;;
            *)      echo "  install them with your package manager, or run the build in a container: scripts/linux.sh scripts/build-php.sh" >&2 ;;
        esac
        echo "  or rerun with SPEEDYSPEC_ALLOW_HOST_INSTALL=1 to let spc install them on this machine" >&2
        exit 1
    fi
}

if [ "${SPEEDYSPEC_ALLOW_HOST_INSTALL:-}" != "1" ]; then
    preflight
fi

spc="$build_dir/spc"

if [ ! -x "$spc" ] || [ "$(sha256_of "$spc")" != "$spc_sha256" ]; then
    echo "build-php.sh: downloading $spc_name"
    curl -fsSL -o "$spc.download" "$spc_base_url/$spc_name"
    actual="$(sha256_of "$spc.download")"
    if [ "$actual" != "$spc_sha256" ]; then
        rm -f "$spc.download"
        echo "build-php.sh: checksum mismatch for $spc_name" >&2
        echo "  expected $spc_sha256" >&2
        echo "  actual   $actual" >&2
        exit 1
    fi
    chmod +x "$spc.download"
    mv "$spc.download" "$spc"
fi

if [ ! -f "$libsodium_tarball" ] || [ "$(sha256_of "$libsodium_tarball")" != "$libsodium_sha256" ]; then
    echo "build-php.sh: downloading libsodium $libsodium_version"
    mkdir -p "$(dirname "$libsodium_tarball")"
    curl -fsSL -o "$libsodium_tarball.download" "$libsodium_url"
    actual="$(sha256_of "$libsodium_tarball.download")"
    if [ "$actual" != "$libsodium_sha256" ]; then
        rm -f "$libsodium_tarball.download"
        echo "build-php.sh: checksum mismatch for libsodium-$libsodium_version.tar.gz" >&2
        echo "  expected $libsodium_sha256" >&2
        echo "  actual   $actual" >&2
        exit 1
    fi
    mv "$libsodium_tarball.download" "$libsodium_tarball"
fi

cd "$build_dir"
if [ "${SPEEDYSPEC_ALLOW_HOST_INSTALL:-}" = "1" ]; then
    "$spc" doctor --auto-fix
elif ! ls "$build_dir"/pkgroot/*/bin/pkg-config >/dev/null 2>&1; then
    # spc looks for pkg-config only in its own .php-build/pkgroot, whatever is on PATH, so it builds one there
    # (inside the repo).
    "$spc" install-pkg pkg-config
fi
"$spc" craft "$repo/craft.yml"

if [ ! -f "$build_dir/buildroot/lib/libphp.a" ]; then
    echo "build-php.sh: $build_dir/buildroot/lib/libphp.a was not produced" >&2
    exit 1
fi

# `php-config --libs` omits libraries that spc's dependencies need (libxml2,
# libiconv, macOS frameworks), so record spc's own list for build.rs.
"$spc" spc-config "$extensions" --with-libs="$libs" --libs --no-motd > "$build_dir/buildroot/link-flags.txt"

check_sodium
# spc must have built from the pinned tarball, not one it fetched itself.
for tarball in "$build_dir"/downloads/libsodium-*.tar.gz; do
    if [ "$(sha256_of "$tarball")" != "$libsodium_sha256" ]; then
        echo "build-php.sh: sodium: spc used $tarball, not the pinned libsodium $libsodium_version" >&2
        exit 1
    fi
done

printf '%s\n' "$stamp_content" > "$stamp"
echo "build-php.sh: built PHP $("$build_dir/buildroot/bin/php-config" --version) in $build_dir/buildroot"
